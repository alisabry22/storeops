// eslint-disable-next-line @typescript-eslint/no-unused-expressions
async (page) => {
  const state = page.__storeopsQA;
  if (!state) throw new Error('Run browser-fixture.js in this isolated session first.');
  const checks = [];
  function assert(condition, description) { if (!condition) throw new Error(description); checks.push(description); }
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('checkbox', { name: 'Starter Monthly studio.monthly', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Premium Yearly studio.premium.yearly', exact: true }).check();
  assert(await page.getByRole('button', { name: 'Continue to prices' }).isDisabled(), 'Different subscription groups cannot be priced as equivalents');
  await page.getByRole('checkbox', { name: 'Starter Yearly studio.yearly', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Same features, different billing periods.' }).check();
  await page.getByRole('button', { name: 'Continue to prices' }).click();
  await page.getByRole('heading', { name: 'Set your prices', exact: true }).waitFor();
  assert(await page.getByRole('combobox', { name: 'Monthly · USD' }).inputValue() === 'p:m:USA:4.99', 'Monthly starts from the actual current US price');
  assert(await page.getByRole('combobox', { name: 'Yearly · USD' }).inputValue() === 'p:y:USA:29.99', 'Yearly starts from the actual current US price');
  assert(!await page.getByRole('combobox', { name: 'Yearly pricing', exact: true }).isVisible(), 'Advanced discount settings are hidden by default');
  await page.screenshot({ path: 'output/playwright/desktop-prices.png', fullPage: true });
  await page.getByText('Discount & price protection', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Yearly pricing', exact: true }).selectOption('target-discount');
  await page.getByRole('spinbutton', { name: 'Target yearly discount (%)' }).fill('0');
  await page.getByRole('button', { name: 'Preview both plans worldwide' }).click();
  assert(await page.getByRole('alert').filter({ hasText: 'Choose an annual discount' }).isVisible(), 'Invalid yearly discounts stop before preview');
  await page.getByRole('spinbutton', { name: 'Target yearly discount (%)' }).fill('40');
  await page.getByRole('combobox', { name: 'Limit changes to existing prices', exact: true }).selectOption('full');
  await page.getByRole('button', { name: 'Preview both plans worldwide' }).click();
  await page.getByRole('heading', { name: 'Preview every country', exact: true }).waitFor();
  assert(state.writes.length === 0, 'Generating a preview never writes store prices');
  assert(await page.getByRole('table').getByRole('row').count() === 9, 'Preview contains every country returned by the store');
  assert(await page.getByRole('button', { name: 'Review & apply both plans' }).isDisabled(), 'Subscriber-impact acknowledgement is required for decreases and large changes');
  await page.getByRole('textbox', { name: 'Search countries or currencies' }).fill('Egypt');
  assert(await page.getByRole('table').getByRole('row').count() === 2, 'Countries can be searched by readable names');
  const row = page.getByRole('table').getByRole('row').filter({ hasText: 'Egypt' });
  assert((await row.innerText()).includes('EGP'), 'Egypt uses its storefront currency');
  await page.getByRole('checkbox', { name: 'All available countries', exact: true }).uncheck();
  await page.getByRole('checkbox', { name: 'Include Egypt', exact: true }).check();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download comparison', exact: true }).click();
  await (await download).saveAs('output/playwright/paired-pricing.csv');
  checks.push('The combined comparison downloads as CSV');
  await page.getByRole('textbox', { name: 'Search countries or currencies' }).fill('');
  await page.screenshot({ path: 'output/playwright/desktop-preview.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.getByRole('table').isHidden(), 'Mobile uses country cards instead of a horizontally scrolling table');
  assert(await page.locator('.pricing-mobile-countries article').count() === 8, 'Mobile cards include every country');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page has no horizontal overflow at 390px');
  await page.getByRole('textbox', { name: 'Search countries or currencies' }).fill('Egypt');
  assert(await page.getByRole('checkbox', { name: 'Include Egypt', exact: true }).isChecked(), 'Country selection is preserved when switching viewport size');
  await page.screenshot({ path: 'output/playwright/mobile-preview.png', fullPage: true });
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/mobile-prices.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile price controls fit at 390px');
  await page.getByRole('radio', { name: /^Growth/ }).check();
  assert(!await page.getByRole('heading', { name: 'Preview every country', exact: true }).isVisible(), 'Changing the pricing goal requires a fresh preview');
  await page.getByRole('button', { name: 'Preview both plans worldwide' }).click();
  await page.getByRole('heading', { name: 'Preview every country', exact: true }).waitFor();
  await page.getByRole('checkbox', { name: 'All available countries', exact: true }).uncheck();
  await page.getByRole('checkbox', { name: 'Include Egypt', exact: true }).check();
  await page.getByRole('checkbox', { name: /I reviewed the subscriber impact/ }).check();
  await page.getByRole('button', { name: 'Review & apply both plans' }).click();
  assert(state.writes.length === 0, 'The final review still has not written any prices');
  await page.getByRole('button', { name: 'Keep reviewing', exact: true }).click();
  assert(state.writes.length === 0, 'Cancelling final confirmation never writes prices');
  await page.getByRole('button', { name: 'Review & apply both plans' }).click();
  await page.getByRole('button', { name: 'Save backups & apply', exact: true }).click();
  await page.getByRole('heading', { name: 'Your pricing results', exact: true }).waitFor();
  assert(await page.getByText('Verified with Apple', { exact: true }).count() === 2, 'Both simulated plans are applied and verified separately');
  assert(state.writes.length === 2, 'Only the selected country is applied to both plans');
  assert(state.writes.every((write) => write.relationships.territory.data.id === 'EGY'), 'Unselected countries are not modified');
  assert(await page.evaluate(() => JSON.parse(localStorage.getItem('storeops.snapshots.v1')).length) === 2, 'Both recovery backups are saved');
  await page.getByRole('button', { name: 'One subscription', exact: true }).click();
  assert(!await page.getByRole('textbox', { name: 'Price spreadsheet' }).isVisible(), 'Single-plan pricing hides spreadsheets until requested');
  assert(!await page.getByText('Name this backup…', { exact: true }).isVisible(), 'Backups do not crowd the main pricing task');
  assert(state.failures.length === 0, 'No JavaScript page errors or unmocked store requests');
  return { passed: checks.length, checks, simulatedWrites: state.writes.length };
}
